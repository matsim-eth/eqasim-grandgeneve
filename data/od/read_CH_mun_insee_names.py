def configure(context):
    context.config("od_documentation_path", "rp_2022/contenu_RP2022_mobpro.pdf")
    context.config("data_path")

    context.stage("data.spatial.ch.municipalities")


def execute(context):
    # Read documentation
    path     = context.config("od_documentation_path")
    data     = context.config("data_path")
    file     = f"{data}/{path}"
    su_lines = []

    with pdfplumber.open(file) as pdf:
        for page in pdf.pages:
            text = page.extract_text()
            if text:  
                for line in text.split("\n"):
                    if line.startswith("SU"):
                        su_lines.append(line)

    insee_codes = pd.DataFrame(columns = ["insee_code_name"])
    insee_codes["insee_code_name"] = su_lines

    insee_codes["insee_code"] = insee_codes["insee_code_name"].str.split(" ").str[0]
    insee_codes["insee_name"] = insee_codes["insee_code_name"].str.split(" ").str[1:].str.join(" ")
    insee_codes["insee_name"] = insee_codes["insee_name"].apply(fix_capitalization)

    insee_codes = insee_codes[["insee_code", "insee_name"]]

    print(insee_codes.head())

    #Import municipalities
    municipalities = context.stage("data.spatial.ch.municipalities")
    municipalities["municipality_name"] = municipalities["municipality_name"].apply(remove_accents)

    # Merge and fix
    insee_merged = insee_codes.merge(municipalities, left_on = "insee_name", right_on = "municipality_name", how = "left")
    merged       = insee_merged[insee_merged["municipality_id"].notna()].copy()
    notmerged    = insee_merged[insee_merged["municipality_id"].isna()][["insee_code", "insee_name"]].copy()

    print(f"Number of merged municipalities: {len(merged)}. Still {len(notmerged)} municipalities to fix.")

    new_merge_info = fix_by_canton_abb(notmerged, municipalities, map_insee_canton_code)

    merged2   = new_merge_info[new_merge_info["municipality_id"].notna()]
    merged    = pd.concat([merged, merged2])
    notmerged = new_merge_info[new_merge_info["municipality_id"].isna()][["insee_code", "insee_name"]].copy()

    print(f"Number of merged municipalities: {len(merged)}. Still {len(notmerged)} municipalities to fix.")

    new_merge_info = fix_by_adding_dashes(notmerged, municipalities)

    merged2   = new_merge_info[new_merge_info["municipality_id"].notna()]
    merged    = pd.concat([merged, merged2])
    notmerged = new_merge_info[new_merge_info["municipality_id"].isna()][["insee_code", "insee_name"]].copy()

    print(f"Number of merged municipalities: {len(merged)}. Still {len(notmerged)} municipalities to fix.")

    new_merge_info = fix_by_updating_name(notmerged, municipalities)

    merged2   = new_merge_info[new_merge_info["municipality_id"].notna()]
    merged    = pd.concat([merged, merged2])
    notmerged = new_merge_info[new_merge_info["municipality_id"].isna()][["insee_code", "insee_name"]].copy()

    print(f"Number of merged municipalities: {len(merged)}. Still {len(notmerged)} municipalities to fix.")

    insee_codes = merged[["insee_code", "insee_name", "municipality_id"]]

    insee_codes.loc[:, "municipality_id"] = "CH" + insee_codes["municipality_id"].astype(int).astype(str).str.zfill(5)

    return insee_codes[["insee_code", "insee_name", "municipality_id"]]

