def remove_accents(text):
    return ''.join(
        c for c in unicodedata.normalize('NFD', text)
        if unicodedata.category(c) != 'Mn'
    )


def fix_capitalization_segment(words):
    PARTICLES = {"am", "an", "auf", "bei", "de", "der", "du", "en", "im", "in", "ob", "sur", "sous", "la", "le", "les", "les", "the", "and", "und", "et", "zum", "zu", "pres", "des"}
    result = []
    in_parens = False
    for i, word in enumerate(words):
        if "(" in word:
            in_parens = True
        if in_parens:
            result.append(word.upper())
        elif i == 0:
            result.append(word.capitalize())
        elif word.lower() in PARTICLES:
            result.append(word.lower())
        else:
            result.append(word.capitalize())
        if ")" in word:
            in_parens = False
    return " ".join(result)


def fix_capitalization(name):
    segments = name.split("-")
    fixed_segments = [fix_capitalization_segment(seg.split()) for seg in segments]
    return "-".join(fixed_segments)


def fix_by_canton_abb(notmerged, mun, map_insee_canton_code):
    invdic = {v: k for k, v in map_insee_canton_code.items()}
    
    notmerged["canton_code"]       = notmerged["insee_code"].str[2].astype(str)
    notmerged["canton_abb"]        = notmerged["canton_code"].map(invdic)
    notmerged["insee_name_prefix"] = notmerged["insee_name"] + " (" + notmerged["canton_abb"] + ")"
    notmerged = notmerged.merge(mun, left_on = "insee_name_prefix", right_on = "municipality_name", how = "left")
    return notmerged


